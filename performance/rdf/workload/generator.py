"""
The benchmark's data: synthetic tables for the STRONG AYA schema, and the
JSON-LD map that describes them.

Nothing here comes from a centre. The schema is the one STRONG AYA publishes
(``schema/``, pinned to a release); the tables and their local codes are
generated from it:

- a first table of patients, one row each;
- follow-up tables with the same columns and the same patients, the way
  centres add data later: under a new file name, linked to the first table
  by the patient's identifier.

The same request (variables, rows, tables, seed) always gives the same
bytes, on any machine and any Python: only ``random.Random.random()`` is
used, seeded with an integer, which Python promises to keep stable. The
workload's digest goes into every result, so two results can be checked to
have measured the same work.
"""

import csv
import hashlib
import io
import json
import random
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, Iterable, List, Mapping, Optional, Sequence, Tuple

SCHEMA_PATH = Path(__file__).resolve().parent / "schema" / "AYA_cancer_schema.jsonld"

IDENTIFIER = "identifier"
IDENTIFIER_COLUMN = "patient_id"
MISSING_TERM = "missing_or_unspecified"
FIRST_TABLE = "patients"

# What a standardised variable (an ICD code, say) holds locally.
_STANDARD_CODES = ("C18.7", "C34.1", "C43.9", "C50.9", "C61", "C71.9", "C81.1")


class WorkloadError(ValueError):
    """A workload that cannot be generated, with what was wrong."""


@dataclass(frozen=True)
class Column:
    """A local column and the schema variable it holds."""

    variable: str
    name: str
    kind: str  # identifier, categorical, continuous or standardised
    # The schema's terms and the local code that stands for each. The
    # missing term's code is the empty cell.
    codes: Tuple[Tuple[str, str], ...] = ()

    @property
    def can_be_missing(self) -> bool:
        return any(term == MISSING_TERM for term, _ in self.codes)

    def term_of(self, value: str) -> Optional[str]:
        """The schema term a local value stands for, if any."""
        for term, code in self.codes:
            if code == value:
                return term
        return None


@dataclass(frozen=True)
class Table:
    name: str
    columns: Tuple[Column, ...]
    rows: Tuple[Tuple[str, ...], ...]
    # The table this one's identifier refers to (None for the first table).
    refers_to: Optional[str] = None

    @property
    def file_name(self) -> str:
        return f"{self.name}.csv"

    def csv(self) -> bytes:
        out = io.StringIO()
        writer = csv.writer(out, lineterminator="\n")
        writer.writerow(column.name for column in self.columns)
        writer.writerows(self.rows)
        return out.getvalue().encode("utf-8")

    def values(self, variable: str) -> List[Tuple[str, str]]:
        """(patient identifier, local value) of every row, for a variable."""
        index = self._index(variable)
        return [(row[0], row[index]) for row in self.rows]

    def column(self, variable: str) -> Column:
        return self.columns[self._index(variable)]

    def _index(self, variable: str) -> int:
        for index, column in enumerate(self.columns):
            if column.variable == variable:
                return index
        raise KeyError(variable)


@dataclass(frozen=True)
class Workload:
    variables: Tuple[str, ...]
    tables: Tuple[Table, ...]
    seed: int

    def table(self, name: str) -> Table:
        for table in self.tables:
            if table.name == name:
                return table
        raise KeyError(name)

    def mapping(self, tables: Optional[Iterable[str]] = None) -> Dict[str, Any]:
        """The JSON-LD map for ``tables`` (all of them by default): the whole
        schema, as a centre's map carries it, and the local mapping of the
        columns these tables have."""
        names = [t.name for t in self.tables] if tables is None else list(tables)
        document = json.loads(json.dumps(load_schema()))
        document["name"] = "Flyover performance benchmark"
        document["description"] = (
            "Generated by performance/rdf/workload: synthetic tables for the "
            "STRONG AYA schema. Not a centre's map."
        )
        document["databases"] = {
            "benchmark": {
                "@id": "mapping:database/benchmark",
                "@type": "mapping:Database",
                "name": "benchmark",
                "tables": {name: _table_mapping(self.table(name)) for name in names},
            }
        }
        return document

    def mapping_bytes(self, tables: Optional[Iterable[str]] = None) -> bytes:
        return json.dumps(self.mapping(tables), indent=2).encode("utf-8")

    def digest(self) -> str:
        """A fingerprint of everything the benchmark sends."""
        sha = hashlib.sha256()
        for table in self.tables:
            sha.update(table.name.encode("utf-8"))
            sha.update(table.csv())
        sha.update(self.mapping_bytes())
        return sha.hexdigest()

    def describe(self) -> Dict[str, Any]:
        return {
            "schema_version": load_schema().get("version"),
            "variables": list(self.variables),
            "tables": [table.name for table in self.tables],
            "rows_per_table": len(self.tables[0].rows),
            "columns_per_table": len(self.tables[0].columns),
            "seed": self.seed,
            "sha256": self.digest(),
        }


@lru_cache(maxsize=1)
def load_schema() -> Dict[str, Any]:
    return json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))


def schema_variables() -> Dict[str, Dict[str, Any]]:
    return load_schema()["schema"]["variables"]


def generate(
    variables: Sequence[str],
    rows: int,
    tables: int,
    seed: int = 1,
    missing: float = 0.1,
) -> Workload:
    """``tables`` tables of ``rows`` patients each, holding ``variables``.

    ``variables`` are names of the schema's variables; the identifier is
    always the first column and need not be listed. ``missing`` is the share
    of empty cells in every column whose variable has a missing term.
    """
    if rows < 1 or tables < 1:
        raise WorkloadError("a workload needs at least one row and one table")
    if not 0 <= missing < 1:
        raise WorkloadError("the share of missing cells is between 0 and 1")
    known = schema_variables()
    names = [name for name in dict.fromkeys(variables) if name != IDENTIFIER]
    unknown = [name for name in names if name not in known]
    if unknown:
        raise WorkloadError(
            f"not variables of the schema: {', '.join(sorted(unknown))}"
        )

    columns = (Column(IDENTIFIER, IDENTIFIER_COLUMN, "identifier"),) + tuple(
        _column(name, known[name]) for name in names
    )
    patients = [f"P{number:06d}" for number in range(1, rows + 1)]
    generated = []
    for index in range(tables):
        name = FIRST_TABLE if index == 0 else f"followup_{index + 1}"
        content = [patients] + [
            _values(column, rows, missing, _stream(seed, name, column.variable))
            for column in columns[1:]
        ]
        generated.append(
            Table(
                name,
                columns,
                tuple(zip(*content)),
                refers_to=None if index == 0 else FIRST_TABLE,
            )
        )
    return Workload((IDENTIFIER,) + tuple(names), tuple(generated), seed)


def _column(name: str, definition: Mapping[str, Any]) -> Column:
    kind = definition.get("dataType", "categorical")
    terms = (definition.get("valueMapping") or {}).get("terms", {})
    book = code_book()
    codes: List[Tuple[str, str]] = []
    for term, mapped in terms.items():
        if term == MISSING_TERM:
            codes.append((term, ""))
        else:
            # Centres code their categories; the codes are not the schema's
            # terms, so the map has to translate them.
            codes.append((term, book[mapped["targetClass"]]))
    return Column(name, name, kind, tuple(codes))


@lru_cache(maxsize=1)
def code_book() -> Dict[str, str]:
    """The centre's code for every class a value can be mapped to: one code
    per class, the same in every column that uses the class.

    This is deliberate. Flyover annotates a value mapping as "the class is
    whatever has this value in this variable", and when two variables give
    one class different codes (yes is 1 here and 2 there), the store's
    reasoning makes the two the same thing: cells get the wrong class, and
    records come back twice. That is a defect of Flyover, in v3.5.0 and
    since, and a centre whose codes differ between columns runs into it. A
    benchmark whose answers are wrong on every version could not tell a
    change that breaks them from one that does not, so its centre keeps one
    code book.
    """
    book: Dict[str, str] = {}
    for definition in schema_variables().values():
        terms = (definition.get("valueMapping") or {}).get("terms", {})
        for term, mapped in terms.items():
            if term != MISSING_TERM:
                book.setdefault(mapped["targetClass"], str(len(book) + 1))
    return book


def _values(
    column: Column, rows: int, missing: float, stream: random.Random
) -> List[str]:
    present = [code for term, code in column.codes if term != MISSING_TERM]
    values = []
    for _ in range(rows):
        # Two draws per cell, always: whether a cell is missing never shifts
        # the values of the cells after it.
        absent, draw = stream.random() < missing, stream.random()
        if absent and column.can_be_missing:
            values.append("")
        elif column.kind == "continuous":
            values.append(str(int(draw * 100)))
        elif column.kind == "standardised":
            values.append(_STANDARD_CODES[int(draw * len(_STANDARD_CODES))])
        elif present:
            values.append(present[int(draw * len(present))])
        else:
            values.append(str(int(draw * 100)))
    return values


def _stream(seed: int, *labels: str) -> random.Random:
    """A stream of its own for every column of every table, so adding a
    variable or a table leaves the others' values as they were."""
    label = "\x1f".join([str(seed), *labels]).encode("utf-8")
    return random.Random(int.from_bytes(hashlib.sha256(label).digest()[:8], "big"))


def _table_mapping(table: Table) -> Dict[str, Any]:
    columns: Dict[str, Any] = {}
    for column in table.columns:
        entry: Dict[str, Any] = {
            "mapsTo": f"schema:variable/{column.variable}",
            "localColumn": column.name,
        }
        if column.codes:
            entry["localMappings"] = dict(column.codes)
        columns[column.variable] = entry
    return {
        "@id": f"mapping:table/{table.name}",
        "@type": "mapping:Table",
        "sourceFile": table.name,
        "columns": columns,
    }
